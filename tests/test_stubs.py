def test_regenerating_replaces_previous_stubs(tmp_path):
    stale = tmp_path / "LibForTests-stubs" / "Old"
    pandasnet.generate_stubs(LIBRARY, output=tmp_path)
    stale.mkdir()
    pandasnet.generate_stubs(LIBRARY, output=tmp_path)
    assert not stale.exists()


def test_foreign_folders_are_not_removed(tmp_path):
    foreign = tmp_path / "LibForTests-stubs"
    foreign.mkdir()
    (foreign / "__init__.pyi").write_text("# hand-written\n")
    (foreign / "keep.txt").write_text("x")
    with pytest.raises(FileExistsError, match="not generated by pandasnet"):
        pandasnet.generate_stubs(LIBRARY, output=tmp_path)
    assert (foreign / "keep.txt").exists()
    assert (foreign / "__init__.pyi").read_text() == "# hand-written\n"


# --- Automatic refresh from load/add_reference ---------------------------------------------------


def _stub_file(output):
    return output / "LibForTests-stubs" / "__init__.pyi"


def test_load_writes_stubs_once_and_skips_when_up_to_date(tmp_path):
    pandasnet.load(LIBRARY, stubs=tmp_path)
    stub = _stub_file(tmp_path)
    first = stub.stat().st_mtime_ns
    assert stub.read_text(encoding="utf-8").splitlines()[1].startswith("# pandasnet-stamp: ")

    pandasnet.load(LIBRARY, stubs=tmp_path)

    assert stub.stat().st_mtime_ns == first
    assert not [path for path in (tmp_path / "LibForTests-stubs").iterdir() if path.name.startswith(".")]


def test_load_regenerates_stale_stubs(tmp_path):
    pandasnet.load(LIBRARY, stubs=tmp_path)
    stub = _stub_file(tmp_path)
    lines = stub.read_text(encoding="utf-8").splitlines(keepends=True)
    stub.write_text("".join([lines[0], "# pandasnet-stamp: outdated\n", "class Removed: ...\n"]), encoding="utf-8")

    pandasnet.load(LIBRARY, stubs=tmp_path)

    text = stub.read_text(encoding="utf-8")
    assert "class Removed" not in text and "class Settings" in text


def test_stub_problems_warn_without_breaking_load(tmp_path):
    foreign = tmp_path / "LibForTests-stubs"
    foreign.mkdir()
    (foreign / "__init__.pyi").write_text("# hand-written\n")

    with pytest.warns(RuntimeWarning, match="could not update editor stubs for LibForTests"):
        ns = pandasnet.load(LIBRARY, stubs=tmp_path)

    assert ns.Item("a", 1.0).Id == "a"
    assert (foreign / "__init__.pyi").read_text() == "# hand-written\n"


def test_stubs_can_be_disabled(tmp_path, monkeypatch):
    pandasnet.load(LIBRARY, stubs=False)
    monkeypatch.setenv("PANDASNET_STUBS", "0")
    monkeypatch.setattr(pandasnet.stubs, "_default_output", lambda output: str(tmp_path))
    pandasnet.load(LIBRARY)
    assert not any(tmp_path.iterdir())

    monkeypatch.setenv("PANDASNET_STUBS", "1")
    pandasnet.load(LIBRARY)
    assert _stub_file(tmp_path).exists()


def test_editor_completion_from_stubs(stubs):
    jedi = pytest.importorskip("jedi")
    output, _ = stubs
    code = (
        "from LibForTests import Processor\nfrom LibForTests.Auto import Portfolio\n"
        "Processor().Run([], None, None).\nPortfolio([])[0].Underlying.\nimport LibForTests\nLibForTests.IPricer."
    )
    script = jedi.Script(code, project=jedi.Project(str(output), added_sys_path=[str(output)]), path=str(output / "x.py"))

    assert {"GetValues"} <= {c.name for c in script.complete(3, len("Processor().Run([], None, None)."))}
    assert {"Id", "Value"} <= {c.name for c in script.complete(4, len("Portfolio([])[0].Underlying."))}
    assert {"Price"} <= {c.name for c in script.complete(6, len("LibForTests.IPricer."))}
