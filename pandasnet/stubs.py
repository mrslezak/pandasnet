"""Generate ``.pyi`` stubs so editors (Pylance, Spyder/Jedi) can complete auto-wrapped CLR namespaces statically."""

import hashlib
import inspect
import os
import shutil
import sysconfig
import tempfile
import time
import warnings

from System import Enum
from System.Reflection import BindingFlags

from . import clrinfo
from .auto import _reference
from .conversion import _keyword

_HEADER = "# Generated by pandasnet.generate_stubs; regenerate after the assembly changes.\n"
_STAMP = "# pandasnet-stamp: "
_FOREIGN = object()
_MODULES = (
    "import collections.abc as _abc\n"
    "import datetime as _dt\n"
    "import typing as _t\n\n"
    "import numpy as _np\n"
    "import pandas as _pd\n"
)
# Helper names used in hints: plain when free, module-qualified when a CLR type in the stub shadows them.
_HELPERS = {
    "Any": ("typing", "_t"),
    "Callable": ("collections.abc", "_abc"),
    "Iterable": ("collections.abc", "_abc"),
    "Iterator": ("collections.abc", "_abc"),
    "Mapping": ("collections.abc", "_abc"),
    "datetime": ("datetime", "_dt"),
    "timedelta": ("datetime", "_dt"),
    "ndarray": ("numpy", "_np"),
    "DataFrame": ("pandas", "_pd"),
    "DatetimeIndex": ("pandas", "_pd"),
}


def _identifier(name: str) -> bool:
    return name.isidentifier() and clrinfo.python_name(name) == name


def _qualname(clr_type) -> str:
    name = clr_type.Name.split("`")[0]
    return f"{_qualname(clr_type.DeclaringType)}.{name}" if clr_type.IsNested else name


def _outermost(clr_type):
    while clr_type.IsNested:
        clr_type = clr_type.DeclaringType
    return clr_type


class _Writer:
    """Renders one namespace's stub, tracking imports of other generated namespaces."""

    def __init__(self, namespace, generated, local_names):
        self.namespace = namespace
        self.generated = generated
        self.imports = set()
        self.lines = []
        self.names = {
            name: f"{alias}.{name}" if name in local_names else name for name, (_, alias) in _HELPERS.items()
        }

    def resolve(self, clr_type):
        outer = _outermost(clr_type)
        if outer.IsGenericType or outer.FullName not in self.generated:
            return None
        if outer.Namespace == self.namespace:
            return _qualname(clr_type)
        self.imports.add(outer.Namespace)
        return f"{outer.Namespace}.{_qualname(clr_type)}"

    def param(self, clr_type):
        return clrinfo.param_hint(clr_type, self.resolve, self.names)

    def result(self, clr_type):
        return clrinfo.result_hint(clr_type, self.resolve, self.names)

    def emit(self, indent, text=""):
        self.lines.append(f"{'    ' * indent}{text}" if text else "")

    def parameters(self, overload, self_parameter):
        rendered = ["self"] if self_parameter else []
        for parameter in overload.parameters:
            name = "self_" if parameter.name == "self" else parameter.name
            default = "" if parameter.default is inspect.Parameter.empty else " = ..."
            rendered.append(f"{name}: {self.param(parameter.clr_type)}{default}")
        return ", ".join(rendered)

    def overloads(self, indent, name, overloads, static, returns):
        for overload in overloads:
            if len(overloads) > 1:
                self.emit(indent, "@_t.overload")
            if static:
                self.emit(indent, "@staticmethod")
            result = "None" if returns is None else self.result(overload.return_type)
            self.emit(indent, f"def {name}({self.parameters(overload, not static)}) -> {result}:")
            self.emit(indent + 1, f'"""{overload.clr_signature}"""')
            self.emit(indent + 1, "...")

    def write_class(self, clr_type, indent):
        name = clr_type.Name.split("`")[0]
        bases = [] if clr_type.IsEnum else clrinfo.direct_bases(clr_type, lambda base: self.resolve(base) is not None)
        self.emit(indent, f"class {name}({', '.join(self.resolve(base) for base in bases)}):" if bases else f"class {name}:")
        doc = clr_type.FullName
        if clr_type.IsInterface or (clr_type.IsAbstract and not clr_type.IsSealed):
            implementations = clrinfo.implementations(clr_type, self.generated.values())
            if implementations:
                doc += "\n\n        Implemented by: " + ", ".join(_qualname(t) for t in implementations)
        self.emit(indent + 1, f'"""{doc}"""')
        if clr_type.IsEnum:
            for member in Enum.GetNames(clr_type):
                if _identifier(member):
                    self.emit(indent + 1, f"{member}: _t.ClassVar[{_qualname(clr_type)}]")
            self.emit(indent)
            return

        constructors = clrinfo.constructors(clr_type)
        if constructors:
            self.overloads(indent + 1, "__init__", constructors, False, None)
        parameters = {_keyword(p.name): p.name for overload in constructors for p in overload.parameters}
        element = clrinfo.element_type(clr_type)
        if element is not None:
            self.emit(indent + 1, f"def __iter__(self) -> {self.names['Iterator']}[{self.result(element)}]: ...")
        if clrinfo.count_property(clr_type):
            self.emit(indent + 1, "def __len__(self) -> int: ...")
        indexer = clrinfo.indexer(clr_type)
        if indexer is not None:
            index_types, value_type, writable = indexer
            key = self.param(index_types[0])
            self.emit(indent + 1, f"def __getitem__(self, key: {key}) -> {self.result(value_type)}: ...")
            if writable:
                self.emit(indent + 1, f"def __setitem__(self, key: {key}, value: {self.param(value_type)}) -> None: ...")

        for member in clrinfo.members(clr_type):
            if not _identifier(member.name):
                continue
            if member.static:
                self.emit(indent + 1, f"{member.name}: _t.ClassVar[{self.result(member.clr_type)}]")
                continue
            self.emit(indent + 1, "@property")
            self.emit(indent + 1, f"def {member.name}(self) -> {self.result(member.clr_type)}:")
            if member.writable:
                note = "settable"
            elif _keyword(member.name) in parameters:
                note = f"read-only; set with {name}(..., {parameters[_keyword(member.name)]}=...)"
            else:
                note = "read-only"
            self.emit(indent + 2, f'"""{note}"""')
            self.emit(indent + 2, "...")
            if member.writable:
                self.emit(indent + 1, f"@{member.name}.setter")
                self.emit(indent + 1, f"def {member.name}(self, value: {self.param(member.clr_type)}) -> None: ...")

        for name, (static, generic, overloads) in clrinfo.methods(clr_type).items():
            if not _identifier(name):
                continue
            if generic:
                self.emit(indent + 1, f"{name}: _t.Any  # generic method: call as {name}(...) or {name}[T](...)")
            else:
                self.overloads(indent + 1, name, overloads, static, True)

        for nested in clr_type.GetNestedTypes(BindingFlags.Public):
            if _identifier(nested.Name.split("`")[0]):
                self.write_class(nested, indent + 1)
        self.emit(indent)

    def render(self, types) -> str:
        local = {clr_type.FullName: clr_type for clr_type in types}
        ordered, seen = [], set()

        def visit(clr_type):
            # Stub classes are defined after the classes they inherit from.
            if clr_type.FullName in seen:
                return
            seen.add(clr_type.FullName)
            for base in clrinfo.direct_bases(clr_type, lambda base: _outermost(base).FullName in local):
                visit(_outermost(base))
            ordered.append(clr_type)

        for clr_type in sorted(types, key=lambda t: t.Name):
            visit(clr_type)
        for clr_type in ordered:
            self.write_class(clr_type, 0)
        plain = {}
        for name, (module, _) in _HELPERS.items():
            if self.names[name] == name:
                plain.setdefault(module, []).append(name)
        helpers = "".join(f"from {module} import {', '.join(names)}\n" for module, names in sorted(plain.items()))
        imports = "".join(f"import {name}\n" for name in sorted(self.imports))
        return f"{_HEADER}{_MODULES}{helpers}{imports}\n\n" + "\n".join(self.lines).rstrip() + "\n"


def _render(loaded, namespace) -> dict:
    """Stub sources by path relative to the namespace's stub folder (sub-namespaces nested)."""
    parts = namespace.split(".")
    by_namespace = {}
    for clr_type in loaded.GetExportedTypes():
        type_namespace = clr_type.Namespace or ""
        if clr_type.IsNested or not (type_namespace == namespace or type_namespace.startswith(namespace + ".")):
            continue
        if clr_type.IsGenericTypeDefinition or not _identifier(clr_type.Name):
            continue
        by_namespace.setdefault(type_namespace, []).append(clr_type)
    generated = {clr_type.FullName: clr_type for types in by_namespace.values() for clr_type in types}

    namespaces = {namespace}
    for type_namespace in by_namespace:
        type_parts = type_namespace.split(".")
        namespaces.update(".".join(type_parts[:depth]) for depth in range(len(parts), len(type_parts) + 1))
    files = {}
    for type_namespace in sorted(namespaces):
        types = by_namespace.get(type_namespace, [])
        local_names = {clr_type.Name for clr_type in types}
        path = os.path.join(*type_namespace.split(".")[len(parts) :], "__init__.pyi")
        files[path] = _Writer(type_namespace, generated, local_names).render(types)
    return files


def _stamp(loaded, namespace) -> str:
    """Identity of the assembly build, namespace and stub generator; unchanged stamp means up-to-date stubs."""
    digest = hashlib.sha256()
    for module_file in (__file__, clrinfo.__file__):
        with open(module_file, "rb") as source:
            digest.update(source.read())
    digest.update(f"{loaded.FullName}|{loaded.ManifestModule.ModuleVersionId}|{namespace}".encode())
    return digest.hexdigest()[:20]


def _existing_stamp(target):
    """Stamp of stubs in target: None if absent, _FOREIGN if target was not written by pandasnet."""
    if not os.path.exists(target):
        return None
    try:
        with open(os.path.join(target, "__init__.pyi"), encoding="utf-8") as stub:
            header, stamp = stub.readline(), stub.readline()
    except OSError:
        return _FOREIGN
    if header != _HEADER:
        return _FOREIGN
    return stamp[len(_STAMP) :].strip() if stamp.startswith(_STAMP) else ""


def _replace(source, destination):
    # Antivirus, indexers and editors briefly lock just-written files on Windows; retry before giving up.
    for delay in (0.05, 0.1, 0.2, 0.4, 0.8):
        try:
            os.replace(source, destination)
            return
        except PermissionError:
            time.sleep(delay)
    os.replace(source, destination)


def _write(output, loaded, namespace, stamp) -> list:
    """Write stubs into a staging folder, then swap it in so editors never see a half-written package."""
    parts = namespace.split(".")
    package = os.path.join(output, f"{parts[0]}-stubs")
    target = os.path.join(package, *parts[1:])
    if _existing_stamp(target) is _FOREIGN:
        raise FileExistsError(f"{target} exists and was not generated by pandasnet; remove it or pass another output")

    files = _render(loaded, namespace)
    files["__init__.pyi"] = files["__init__.pyi"].replace(_HEADER, f"{_HEADER}{_STAMP}{stamp}\n", 1)

    written = []
    # Parent namespaces need (empty) package stubs so the editor can import the generated ones.
    for depth in range(1, len(parts)):
        init = os.path.join(package, *parts[1:depth], "__init__.pyi")
        if not os.path.exists(init):
            os.makedirs(os.path.dirname(init), exist_ok=True)
            with open(init, "w", encoding="utf-8") as stub:
                stub.write(_HEADER)
            written.append(init)

    parent = os.path.dirname(target)
    os.makedirs(parent, exist_ok=True)
    staging = tempfile.mkdtemp(prefix=f".{parts[-1]}-stubs-", dir=parent)
    try:
        for path, text in files.items():
            os.makedirs(os.path.join(staging, os.path.dirname(path)), exist_ok=True)
            with open(os.path.join(staging, path), "w", encoding="utf-8") as stub:
                stub.write(text)
        retired = None
        if os.path.exists(target):
            retired = tempfile.mkdtemp(prefix=f".{parts[-1]}-stubs-old-", dir=parent)
            os.rmdir(retired)
            _replace(target, retired)
        try:
            _replace(staging, target)
        except OSError:
            if retired is not None and not os.path.exists(target):
                _replace(retired, target)
            raise
        if retired is not None:
            shutil.rmtree(retired, ignore_errors=True)
    finally:
        if os.path.exists(staging):
            shutil.rmtree(staging, ignore_errors=True)
    return written + [os.path.join(target, path) for path in files]


def _default_output(output):
    return sysconfig.get_paths()["purelib"] if output is None else os.fspath(output)


def generate_stubs(assembly, output=None, namespace=None) -> list:
    """Write ``.pyi`` stubs for an assembly's namespace so editors autocomplete it without running code.

    Stubs mirror the auto-wrapped classes from :func:`add_reference`/:func:`load`: Python-facing
    parameter and return types, overloads, properties, enums and nested types. They are written as a
    PEP 561 stub package (``<RootNamespace>-stubs``) into ``output`` (default: the active environment's
    site-packages, where Pylance and Spyder/Jedi find them automatically). Editors resolve
    ``from MyLib import Engine`` with these stubs, so prefer :func:`add_reference` imports in editor code.
    :func:`load` and :func:`add_reference` already refresh stale stubs; this always rewrites them.
    Returns the written file paths.
    """

    loaded, namespace = _reference(assembly, namespace)
    return _write(_default_output(output), loaded, namespace, _stamp(loaded, namespace))


def refresh_stubs(loaded, namespace, output=None) -> bool:
    """Regenerate stubs only when the assembly build or generator changed; never raises. True if written."""
    try:
        output = _default_output(output)
        stamp = _stamp(loaded, namespace)
        parts = namespace.split(".")
        target = os.path.join(output, f"{parts[0]}-stubs", *parts[1:])
        existing = _existing_stamp(target)
        if existing == stamp:
            return False
        if existing is _FOREIGN:
            raise FileExistsError(f"{target} exists and was not generated by pandasnet")
        _write(output, loaded, namespace, stamp)
        return True
    except Exception as error:
        warnings.warn(
            f"pandasnet could not update editor stubs for {namespace}: {error}. "
            "Loading continues; pass stubs=False or set PANDASNET_STUBS=0 to skip this.",
            RuntimeWarning,
            stacklevel=4,
        )
        return False
